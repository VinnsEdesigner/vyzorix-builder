#!/usr/bin/env python3
"""Embed builders/*.Dockerfile into a C++ header.

The first-class adapters' images COPY the project in and run a build, so they
must be built with the project as context. Embedding the Dockerfiles makes the
binary self-contained: it needs no builders/ directory at run time.
"""
import glob, os, sys

out = sys.argv[1]
files = sorted(glob.glob("builders/*.Dockerfile"))

with open(out, "w") as f:
    f.write("// Generated by tooling_embed.py from builders/*.Dockerfile. DO NOT EDIT.\n")
    f.write("#pragma once\n\n#include <string>\n\nnamespace vyzorix::containerbuild {\n\n")
    def ident(lang):
        # A C++ identifier cannot contain '-'; node-webroot becomes node_webroot.
        return lang.replace("-", "_")

    for path in files:
        lang = os.path.basename(path).replace(".Dockerfile", "")
        body = open(path).read()
        # A raw string literal: the delimiter keeps a Dockerfile's quotes and
        # backslashes intact without escaping.
        f.write(f"inline const char* kDockerfile_{ident(lang)} = R\"DOCKERFILE({body})DOCKERFILE\";\n\n")
    f.write("// bundled_dockerfile returns the embedded Dockerfile for a language, or\n")
    f.write("// nullptr when the language has no bundled builder.\n")
    f.write("inline const char* bundled_dockerfile(const std::string& lang) {\n")
    for path in files:
        lang = os.path.basename(path).replace(".Dockerfile", "")
        f.write(f'    if (lang == "{lang}") return kDockerfile_{ident(lang)};\n')
    f.write("    return nullptr;\n}\n\n}  // namespace vyzorix::containerbuild\n")

# Embed the base-image pins, so the binary applies them without reading a file.
pins_path = "builders/pins.txt"
pins = open(pins_path).read() if os.path.exists(pins_path) else ""
with open(out, "a") as f:
    f.write("\n")
    f.write("// kImagePins is builders/pins.txt, embedded (contract R8).\n")
    f.write("inline const char* kImagePins = R\"PINS(" + pins + ")PINS\";\n")

print(f"wrote {out} ({len(files)} Dockerfiles, pins {len(pins)} bytes)")